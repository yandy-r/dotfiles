#!/usr/bin/env bash

set -euo pipefail

SCRIPT_NAME="$(basename "${BASH_SOURCE[0]}")"
readonly SCRIPT_NAME
readonly LOG_PREFIX="[ONEDRIVE-MAIN]"

CONFIG_BASE="${XDG_CONFIG_HOME:-${HOME}/.config}"
CONFDIR="${CONFIG_BASE}/onedrive"
SYNC_DIR="${HOME}/OneDrive"
ENABLE_SERVICE=false
ENABLE_LINGER=true
INITIAL_SYNC=false
DRY_RUN=false
ONEDRIVE_BIN=""

usage() {
    cat <<EOF
Usage: $SCRIPT_NAME [OPTIONS]

Configure the main onedrive-abraunegg profile, including OneDrive Business
shared files.

Options:
    --sync-dir DIR          Local sync directory (default: ~/OneDrive)
    --confdir DIR           onedrive config directory (default: ~/.config/onedrive)
    --enable-service        Create, enable, and start the main systemd user service
    --no-linger             Do not enable systemd user lingering for boot startup
    --initial-sync          Run one foreground shared-files sync after config update
    --dry-run               Show actions without changing files
    -h, --help              Show this help message

Examples:
    $SCRIPT_NAME --initial-sync
    $SCRIPT_NAME --sync-dir ~/OneDrive --enable-service

Notes:
    This writes sync_business_shared_items = "true" to the selected config.
    A manual shared-files sync is:

        onedrive --confdir ~/.config/onedrive --sync-shared-files --sync
EOF
    exit "${1:-0}"
}

log() {
    echo "${LOG_PREFIX} $*" >&2
}

error_exit() {
    log "ERROR: $1"
    exit "${2:-1}"
}

command_exists() {
    command -v "$1" >/dev/null 2>&1
}

require_value() {
    local option="$1"
    local value="${2:-}"

    [[ -n "$value" ]] || error_exit "${option} requires a value"
}

validate_config_value() {
    local label="$1"
    local value="$2"

    case "$value" in
        *$'\n'*|*$'\r'*|*\"*|*\\*)
            error_exit "${label} cannot contain quotes, backslashes, or newlines"
            ;;
    esac
}

expand_path() {
    local path="$1"
    case "$path" in
        \~) printf '%s\n' "$HOME" ;;
        \~/*) printf '%s/%s\n' "$HOME" "${path#~/}" ;;
        *) printf '%s\n' "$path" ;;
    esac
}

systemd_escape_specifiers() {
    printf '%s' "$1" | sed 's/%/%%/g'
}

run() {
    if [[ "$DRY_RUN" == "true" ]]; then
        log "DRY-RUN: $*"
        return 0
    fi

    "$@"
}

write_config() {
    local config_file="${CONFDIR}/config"
    local temp_file
    local has_config=false

    log "Creating config directory: ${CONFDIR}"
    run mkdir -p "$CONFDIR"

    log "Creating sync directory: ${SYNC_DIR}"
    run mkdir -p "$SYNC_DIR"

    if [[ -e "$config_file" ]]; then
        has_config=true
        log "Updating onedrive config: ${config_file}"
    else
        log "Writing onedrive config: ${config_file}"
    fi

    if [[ "$DRY_RUN" == "true" ]]; then
        return 0
    fi

    umask 077

    if [[ "$has_config" != "true" ]]; then
        cat > "$config_file" <<EOF
# Generated by ${SCRIPT_NAME}
sync_dir = "${SYNC_DIR}"
sync_business_shared_items = "true"
disable_version_check = "true"
EOF
        return 0
    fi

    temp_file="$(mktemp "${config_file}.tmp.XXXXXX")"
    awk -v sync_dir="$SYNC_DIR" '
        BEGIN {
            saw_sync_dir = 0
            saw_shared = 0
            saw_version_check = 0
        }
        /^[[:space:]]*sync_dir[[:space:]]*=/ {
            saw_sync_dir = 1
            print "sync_dir = \"" sync_dir "\""
            next
        }
        /^[[:space:]]*sync_business_shared_items[[:space:]]*=/ {
            saw_shared = 1
            print "sync_business_shared_items = \"true\""
            next
        }
        /^[[:space:]]*disable_version_check[[:space:]]*=/ {
            saw_version_check = 1
            print "disable_version_check = \"true\""
            next
        }
        { print }
        END {
            if (!saw_sync_dir) {
                print "sync_dir = \"" sync_dir "\""
            }
            if (!saw_shared) {
                print "sync_business_shared_items = \"true\""
            }
            if (!saw_version_check) {
                print "disable_version_check = \"true\""
            }
        }
    ' "$config_file" > "$temp_file"
    chmod 600 "$temp_file"
    mv "$temp_file" "$config_file"
}

write_service() {
    local service_dir="${CONFIG_BASE}/systemd/user"
    local service_name="onedrive.service"
    local service_file="${service_dir}/${service_name}"
    local escaped_confdir
    local escaped_onedrive_bin

    if [[ "$CONFDIR" =~ [[:space:]] ]]; then
        error_exit "Service generation does not support whitespace in --confdir: ${CONFDIR}"
    fi

    if [[ "$ONEDRIVE_BIN" =~ [[:space:]] ]]; then
        error_exit "Service generation does not support whitespace in onedrive path: ${ONEDRIVE_BIN}"
    fi

    escaped_confdir="$(systemd_escape_specifiers "$CONFDIR")"
    escaped_onedrive_bin="$(systemd_escape_specifiers "$ONEDRIVE_BIN")"

    log "Writing systemd user service: ${service_file}"
    run mkdir -p "$service_dir"

    if [[ "$DRY_RUN" != "true" ]]; then
        cat > "$service_file" <<EOF
[Unit]
Description=OneDrive main sync
Documentation=https://github.com/abraunegg/onedrive
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStartPre=/bin/sh -c 'sleep 15'
ExecStart=${escaped_onedrive_bin} --monitor --sync-shared-files --confdir ${escaped_confdir}
Restart=on-failure
RestartSec=30

[Install]
WantedBy=default.target
EOF
    fi

    run systemctl --user daemon-reload
    enable_linger_if_needed

    log "Enabling and starting ${service_name}"
    run systemctl --user enable --now "$service_name"
}

run_initial_sync() {
    log "Running initial foreground sync with shared files"
    run "$ONEDRIVE_BIN" --confdir "$CONFDIR" --sync-shared-files --sync
}

enable_linger_if_needed() {
    local user_name="${USER:-}"

    if [[ "$ENABLE_LINGER" != "true" ]]; then
        log "Skipping systemd lingering; service will start at user login."
        return 0
    fi

    command_exists loginctl || error_exit "loginctl command not found; re-run with --no-linger to only enable login startup"
    [[ -n "$user_name" ]] || error_exit "USER is not set; cannot enable systemd lingering"

    if loginctl show-user "$user_name" --property=Linger --value 2>/dev/null | grep -qx yes; then
        log "Systemd lingering already enabled for ${user_name}"
        return 0
    fi

    log "Enabling systemd lingering for ${user_name} so the user service can start at boot"
    run loginctl enable-linger "$user_name"
}

parse_args() {
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --sync-dir)
                require_value "$1" "${2:-}"
                SYNC_DIR="$(expand_path "${2:-}")"
                shift 2
                ;;
            --confdir)
                require_value "$1" "${2:-}"
                CONFDIR="$(expand_path "${2:-}")"
                shift 2
                ;;
            --enable-service)
                ENABLE_SERVICE=true
                shift
                ;;
            --no-linger)
                ENABLE_LINGER=false
                shift
                ;;
            --initial-sync)
                INITIAL_SYNC=true
                shift
                ;;
            --dry-run)
                DRY_RUN=true
                shift
                ;;
            -h|--help)
                usage 0
                ;;
            *)
                error_exit "Unknown argument: $1"
                ;;
        esac
    done
}

main() {
    parse_args "$@"

    command_exists onedrive || error_exit "onedrive command not found"
    ONEDRIVE_BIN="$(command -v onedrive)"

    validate_config_value "--sync-dir" "$SYNC_DIR"
    validate_config_value "--confdir" "$CONFDIR"

    log "Config: ${CONFDIR}"
    log "Sync:   ${SYNC_DIR}"

    write_config

    if [[ "$INITIAL_SYNC" == "true" ]]; then
        run_initial_sync
    fi

    if [[ "$ENABLE_SERVICE" == "true" ]]; then
        write_service
    else
        log "Service not enabled. To sync manually: onedrive --confdir '${CONFDIR}' --sync-shared-files --sync"
        log "To monitor continuously later, re-run with --enable-service."
    fi

    log "Complete"
}

main "$@"
