// fixtureInfo is a representative Debian-family host used by the rendering
// and shell-parity tests.
var fixtureInfo = Info{
	OS:        OSDebian,
	Arch:      ArchX86_64,
	PkgMgr:    PkgMgrAPT,
	Container: ContainerNone,
	Distro:    "ubuntu",
	Codename:  "noble",
	VersionID: "24.04",
	Desktop:   true,
}

const fixtureEnv = "# Generated by `dotf platform --write`; do not edit.\n" +
	"export DOTFILES_PLATFORM_SCHEMA=1\n" +
	"export DOTFILES_PLATFORM_HOST=build-host.local\n" +
	"export DOTFILES_OS=debian\n" +
	"export DOTFILES_ARCH=x86_64\n" +
	"export DOTFILES_CONTAINER=none\n" +
	"export DOTFILES_PKG_MGR=apt\n" +
	"export DOTFILES_DISTRO=ubuntu\n" +
	"export DOTFILES_CODENAME=noble\n" +
	"export DOTFILES_HOMEBREW_PATH=/home/linuxbrew/.linuxbrew\n"

func TestWriteEnv_Fixture(t *testing.T) {
	var buf bytes.Buffer
	if err := WriteEnv(&buf, fixtureInfo, "build-host.local", "/home/linuxbrew/.linuxbrew"); err != nil {
		t.Fatal(err)
	}
	if got := buf.String(); got != fixtureEnv {
		t.Errorf("WriteEnv =\n%s\nwant\n%s", got, fixtureEnv)
	}
}

func TestEnvLines_SanitizesValues(t *testing.T) {
	tests := []struct {
		name, in, want string
	}{
		{"plain", "cachyos", "cachyos"},
		{"path", "/opt/homebrew", "/opt/homebrew"},
		{"allowed punctuation", "a.b_c/d+e-f", "a.b_c/d+e-f"},
		{"empty", "", ""},
		{"command substitution", "$(touch /tmp/pwned)", ""},
		{"backticks", "`id`", ""},
		{"space", "my host", ""},
		{"double quote", `x"y`, ""},
		{"single quote", "x'y", ""},
		{"newline injection", "x\nexport DOTFILES_OS=evil", ""},
		{"semicolon", "x;rm -rf ~", ""},
		{"equals", "a=b", ""},
		{"non-ascii", "héllo", ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			info := Info{OS: OSLinux, Distro: tt.in, Codename: tt.in}
			lines := EnvLines(info, tt.in, tt.in)
			if len(lines) != len(EnvKeys)+1 {
				t.Fatalf("got %d lines, want %d", len(lines), len(EnvKeys)+1)
			}
			for _, key := range []string{"DOTFILES_PLATFORM_HOST", "DOTFILES_DISTRO", "DOTFILES_CODENAME", "DOTFILES_HOMEBREW_PATH"} {
				want := "export " + key + "=" + tt.want
				found := false
				for _, l := range lines {
					if l == want {
						found = true
					}
				}
				if !found {
					t.Errorf("missing %q in %q", want, lines)
				}
			}
		})
	}
}

func TestCachePath(t *testing.T) {
	tests := []struct {
		name, xdg, home, want string
		wantErr               bool
	}{
		{name: "absolute xdg wins", xdg: "/x/cache", home: "/home/u", want: "/x/cache/dotfiles/platform.env"},
		{name: "relative xdg ignored", xdg: "rel/cache", home: "/home/u", want: "/home/u/.cache/dotfiles/platform.env"},
		{name: "unset xdg", home: "/home/u", want: "/home/u/.cache/dotfiles/platform.env"},
		{name: "no home and no xdg", wantErr: true},
		{name: "absolute xdg without home", xdg: "/x", want: "/x/dotfiles/platform.env"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			getenv := func(k string) string {
				if k == "XDG_CACHE_HOME" {
					return tt.xdg
				}
				return ""
			}
			got, err := CachePath(getenv, tt.home)
			if (err != nil) != tt.wantErr {
				t.Fatalf("err = %v, wantErr %v", err, tt.wantErr)
			}
			if got != tt.want {
				t.Errorf("CachePath = %q, want %q", got, tt.want)
			}
		})
	}
}

func TestWriteEnvCache(t *testing.T) {
	tests := []struct {
		name    string
		setup   func(t *testing.T, root string) string // returns target path
		wantErr bool
	}{
		{
			name:  "creates parent and file",
			setup: func(_ *testing.T, root string) string { return filepath.Join(root, "dotfiles", "platform.env") },
		},
		{
			name: "replaces existing file",
			setup: func(t *testing.T, root string) string {
				p := filepath.Join(root, "platform.env")
				if err := os.WriteFile(p, []byte("old"), 0o644); err != nil {
					t.Fatal(err)
				}
				return p
			},
		},
		{
			// The shell's give-up marker must not outlive a successful write.
			name: "clears shell retry marker",
			setup: func(t *testing.T, root string) string {
				p := filepath.Join(root, "platform.env")
				if err := os.WriteFile(p+".attempted", nil, 0o600); err != nil {
					t.Fatal(err)
				}
				return p
			},
		},
		{
			name: "refuses symlinked target",
			setup: func(t *testing.T, root string) string {
				p := filepath.Join(root, "platform.env")
				if err := os.Symlink(filepath.Join(root, "victim"), p); err != nil {
					t.Fatal(err)
				}
				return p
			},
			wantErr: true,
		},
		{
			name: "refuses symlinked parent",
			setup: func(t *testing.T, root string) string {
				realDir := filepath.Join(root, "real")
				if err := os.Mkdir(realDir, 0o700); err != nil {
					t.Fatal(err)
				}
				if err := os.Symlink(realDir, filepath.Join(root, "dotfiles")); err != nil {
					t.Fatal(err)
				}
				return filepath.Join(root, "dotfiles", "platform.env")
			},
			wantErr: true,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			root := t.TempDir()
			path := tt.setup(t, root)
			err := WriteEnvCache(path, []byte(fixtureEnv))
			if (err != nil) != tt.wantErr {
				t.Fatalf("err = %v, wantErr %v", err, tt.wantErr)
			}
			if tt.wantErr {
				if _, serr := os.Stat(filepath.Join(root, "victim")); !errors.Is(serr, os.ErrNotExist) {
					t.Error("write followed the symlinked target")
				}
				if _, serr := os.Stat(filepath.Join(root, "real", "platform.env")); !errors.Is(serr, os.ErrNotExist) {
					t.Error("write followed the symlinked parent")
				}
				return
			}
			fi, err := os.Lstat(path)
			if err != nil {
				t.Fatal(err)
			}
			if !fi.Mode().IsRegular() || fi.Mode().Perm() != 0o600 {
				t.Errorf("mode = %v, want regular 0600", fi.Mode())
			}
			if data, _ := os.ReadFile(path); string(data) != fixtureEnv {
				t.Errorf("content = %q", data)
			}
			entries, _ := os.ReadDir(filepath.Dir(path))
			if len(entries) != 1 {
				t.Errorf("leftover temp files: %v", entries)
			}
		})
	}
}

func TestHomebrewPrefix(t *testing.T) {
	tests := []struct {
		name    string
		brew    bool
		brewOut string
		brewErr error
		info    Info
		want    string
	}{
		{name: "brew on path", brew: true, brewOut: "/custom/brew\n", info: Info{OS: OSMacOS, Arch: ArchARM64}, want: "/custom/brew"},
		{name: "brew --prefix fails", brew: true, brewErr: errors.New("boom"), info: Info{OS: OSMacOS, Arch: ArchARM64}, want: "/opt/homebrew"},
		{name: "macos arm64", info: Info{OS: OSMacOS, Arch: ArchARM64}, want: "/opt/homebrew"},
		{name: "macos x86_64", info: Info{OS: OSMacOS, Arch: ArchX86_64}, want: "/usr/local"},
		{name: "debian", info: Info{OS: OSDebian, Arch: ArchX86_64}, want: "/home/linuxbrew/.linuxbrew"},
		{name: "generic linux", info: Info{OS: OSLinux}, want: "/home/linuxbrew/.linuxbrew"},
		{name: "wsl", info: Info{OS: OSWSL}, want: "/home/linuxbrew/.linuxbrew"},
		{name: "windows", info: Info{OS: OSWindows}, want: ""},
		{name: "unknown", info: Info{OS: OSUnknown}, want: ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			f := exec.NewFake()
			if tt.brew {
				f.AddPath("brew", "/usr/bin/brew")
				f.AddCommand("brew", []string{"--prefix"}, []byte(tt.brewOut), tt.brewErr)
			}
			if got := HomebrewPrefix(f, tt.info); got != tt.want {
				t.Errorf("HomebrewPrefix = %q, want %q", got, tt.want)
			}
		})
	}
}

// TestEnvCache_ShellParity proves the Go writer and the shell loader
// (common/platform.sh:_dotfiles_load_platform_cache) agree on the format: a
// Go-rendered file loads and round-trips every key, and tampered files are
// rejected.
func TestEnvCache_ShellParity(t *testing.T) {
	bash, err := osexec.LookPath("bash")
	if err != nil {
		t.Skip("bash not on PATH")
	}
	if runtime.GOOS == "windows" {
		t.Skip("shell loader is POSIX-only")
	}
	_, thisFile, _, _ := runtime.Caller(0)
	platformSh := filepath.Join(filepath.Dir(thisFile), "..", "..", "common", "platform.sh")

	// The loader rejects a cache whose arch differs from the running shell's
	// $HOSTTYPE, or that says container=none inside a container (CI runs this
	// in fedora:latest under Docker), so render the fixture for this host.
	info := fixtureInfo
	switch runtime.GOARCH {
	case "amd64":
		info.Arch = ArchX86_64
	case "arm64":
		info.Arch = ArchARM64
	}
	if fileExists("/.dockerenv") || fileExists("/run/.containerenv") {
		info.Container = ContainerDocker
	}

	const host = "parity-host"
	var good bytes.Buffer
	if err := WriteEnv(&good, info, host, "/home/linuxbrew/.linuxbrew"); err != nil {
		t.Fatal(err)
	}
	want := map[string]string{
		"DOTFILES_PLATFORM_SCHEMA": "1",
		"DOTFILES_PLATFORM_HOST":   host,
		"DOTFILES_OS":              "debian",
		"DOTFILES_ARCH":            string(info.Arch),
		"DOTFILES_CONTAINER":       string(info.Container),
		"DOTFILES_PKG_MGR":         "apt",
		"DOTFILES_DISTRO":          "ubuntu",
		"DOTFILES_CODENAME":        "noble",
		"DOTFILES_HOMEBREW_PATH":   "/home/linuxbrew/.linuxbrew",
	}

	tests := []struct {
		name    string
		content string
		host    string
		wantOK  bool
	}{
		{name: "go-rendered file loads", content: good.String(), host: host, wantOK: true},
		{name: "unknown key", content: good.String() + "export DOTFILES_EVIL=1\n", host: host},
		{name: "bad value", content: strings.Replace(good.String(), "DOTFILES_DISTRO=ubuntu", "DOTFILES_DISTRO=$(id)", 1), host: host},
		{name: "wrong host", content: good.String(), host: "other-host"},
		{name: "missing key", content: strings.Replace(good.String(), "export DOTFILES_CODENAME=noble\n", "", 1), host: host},
		{name: "wrong schema", content: strings.Replace(good.String(), "SCHEMA=1", "SCHEMA=2", 1), host: host},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			file := filepath.Join(t.TempDir(), "platform.env")
			if err := os.WriteFile(file, []byte(tt.content), 0o600); err != nil {
				t.Fatal(err)
			}
			script := `. "$1" || exit 90
_dotfiles_load_platform_cache "$2" || exit 91
for k in ` + strings.Join(EnvKeys, " ") + `; do
  eval "printf '%s=%s\n' \"\$k\" \"\${$k-<unset>}\""
done`
			cmd := osexec.Command(bash, "--noprofile", "--norc", "-c", script, "parity", platformSh, file)
			cmd.Env = []string{
				"PATH=" + os.Getenv("PATH"),
				"HOME=" + t.TempDir(),
				"DOTFILES_NO_AUTO_SETUP=1",
				"HOSTNAME=" + tt.host,
			}
			out, err := cmd.Output()
			code := 0
			var ee *osexec.ExitError
			if errors.As(err, &ee) {
				code = ee.ExitCode()
			} else if err != nil {
				t.Fatal(err)
			}
			if code == 90 {
				t.Fatalf("sourcing %s failed", platformSh)
			}
			if !tt.wantOK {
				if code != 91 {
					t.Errorf("loader accepted tampered file (exit %d, out %q)", code, out)
				}
				return
			}
			if code != 0 {
				t.Fatalf("loader rejected Go-rendered file (exit %d)", code)
			}
			got := map[string]string{}
			for _, l := range strings.Split(strings.TrimSpace(string(out)), "\n") {
				k, v, _ := strings.Cut(l, "=")
				got[k] = v
			}
			for k, v := range want {
				if got[k] != v {
					t.Errorf("%s = %q, want %q", k, got[k], v)
				}
			}
		})
	}
}
