package platform

import (
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/yandy-r/dotfiles/internal/exec"
)

// EnvSchema is the platform env cache format version. The shell loader
// (common/platform.sh:_dotfiles_load_platform_cache) rejects any other value.
const EnvSchema = "1"

// envHeader is the single leading comment line of the rendered env file.
const envHeader = "# Generated by `dotf platform --write`; do not edit."

// EnvKeys is the exact, ordered key whitelist of the platform env file. The
// shell loader accepts only these keys and requires every one of them.
var EnvKeys = []string{
	"DOTFILES_PLATFORM_SCHEMA",
	"DOTFILES_PLATFORM_HOST",
	"DOTFILES_OS",
	"DOTFILES_ARCH",
	"DOTFILES_CONTAINER",
	"DOTFILES_PKG_MGR",
	"DOTFILES_DISTRO",
	"DOTFILES_CODENAME",
	"DOTFILES_HOMEBREW_PATH",
}

// Homebrew prefix defaults used when brew is not on PATH, matching the shell
// fallback common/platform.sh:get_homebrew_path.
const (
	homebrewMacARM   = "/opt/homebrew"
	homebrewMacIntel = "/usr/local"
	homebrewLinux    = "/home/linuxbrew/.linuxbrew"
)

// HomebrewPrefix returns the Homebrew prefix for info: the trimmed output of
// `brew --prefix` when brew is on PATH (via r), else the conventional default
// for the platform (/opt/homebrew on macOS arm64, /usr/local on other macOS,
// /home/linuxbrew/.linuxbrew on the Linux family), else "".
func HomebrewPrefix(r exec.Runner, info Info) string {
	if _, err := r.LookPath("brew"); err == nil {
		if out, err := r.Output("brew", "--prefix"); err == nil {
			if p := strings.TrimSpace(string(out)); p != "" {
				return p
			}
		}
	}
	switch {
	case info.OS == OSMacOS && info.Arch == ArchARM64:
		return homebrewMacARM
	case info.OS == OSMacOS:
		return homebrewMacIntel
	case IsLinuxFamily(info.OS):
		return homebrewLinux
	default:
		return ""
	}
}

// envValueOK reports whether v matches the shell-safe charset
// ^[A-Za-z0-9._/+-]*$ that the shell loader accepts unquoted.
func envValueOK(v string) bool {
	for i := range len(v) {
		c := v[i]
		switch {
		case c >= 'A' && c <= 'Z', c >= 'a' && c <= 'z', c >= '0' && c <= '9':
		case c == '.', c == '_', c == '/', c == '+', c == '-':
		default:
			return false
		}
	}
	return true
}

// sanitizeEnvValue returns v if it is shell-safe, else "".
func sanitizeEnvValue(v string) string {
	if envValueOK(v) {
		return v
	}
	return ""
}

// EnvLines renders info, host, and homebrew as the platform env file lines
// (header comment first, then one `export KEY=VALUE` per EnvKeys entry, in
// order). Any value outside the shell-safe charset is replaced with "".
func EnvLines(info Info, host, homebrew string) []string {
	values := []string{
		EnvSchema,
		host,
		string(info.OS),
		string(info.Arch),
		string(info.Container),
		string(info.PkgMgr),
		info.Distro,
		info.Codename,
		homebrew,
	}
	lines := make([]string, 0, len(EnvKeys)+1)
	lines = append(lines, envHeader)
	for i, k := range EnvKeys {
		lines = append(lines, "export "+k+"="+sanitizeEnvValue(values[i]))
	}
	return lines
}

// WriteEnv writes EnvLines to w, newline-terminated.
func WriteEnv(w io.Writer, info Info, host, homebrew string) error {
	_, err := io.WriteString(w, strings.Join(EnvLines(info, host, homebrew), "\n")+"\n")
	return err
}

// CachePath returns the platform env cache path,
// ${XDG_CACHE_HOME:-$HOME/.cache}/dotfiles/platform.env. XDG_CACHE_HOME is
// honored only when absolute (per the XDG spec); home must be non-empty when
// it is not.
func CachePath(getenv func(string) string, home string) (string, error) {
	base := getenv("XDG_CACHE_HOME")
	if !filepath.IsAbs(base) {
		if home == "" {
			return "", errors.New("platform env cache: cannot resolve $HOME")
		}
		base = filepath.Join(home, ".cache")
	}
	return filepath.Join(base, "dotfiles", "platform.env"), nil
}

// WriteEnvCache atomically replaces the file at path with content (mode
// 0600). The parent directory is created 0700 if missing. It refuses to
// write when the parent directory or the target is a symlink, so a planted
// link cannot redirect the write. The content is written to a temp file in
// the same directory, fsynced, then renamed over path.
func WriteEnvCache(path string, content []byte) (err error) {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return fmt.Errorf("platform env cache: %w", err)
	}
	if fi, err := os.Lstat(dir); err != nil {
		return fmt.Errorf("platform env cache: %w", err)
	} else if fi.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("platform env cache: refusing symlinked directory %s", dir)
	}
	if fi, err := os.Lstat(path); err == nil && fi.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("platform env cache: refusing symlinked file %s", path)
	} else if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("platform env cache: %w", err)
	}

	tmp, err := os.CreateTemp(dir, ".platform.env.*")
	if err != nil {
		return fmt.Errorf("platform env cache: %w", err)
	}
	tmpName := tmp.Name()
	defer func() {
		if err != nil {
			_ = tmp.Close()
			_ = os.Remove(tmpName)
		}
	}()
	// CreateTemp already uses 0600; Chmod makes it explicit regardless of umask.
	if err = tmp.Chmod(0o600); err != nil {
		return fmt.Errorf("platform env cache: %w", err)
	}
	if _, err = tmp.Write(content); err != nil {
		return fmt.Errorf("platform env cache: %w", err)
	}
	if err = tmp.Sync(); err != nil {
		return fmt.Errorf("platform env cache: %w", err)
	}
	if err = tmp.Close(); err != nil {
		return fmt.Errorf("platform env cache: %w", err)
	}
	if err = os.Rename(tmpName, path); err != nil {
		return fmt.Errorf("platform env cache: %w", err)
	}
	// The shell leaves this marker after a `dotf platform --write` that wrote
	// nothing (old binary, unwritable dir) so it stops retrying on every start.
	_ = os.Remove(path + ".attempted")
	return nil
}
