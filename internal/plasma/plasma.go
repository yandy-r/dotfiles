package plasma

// This file holds the engine's vocabulary: the run switches, the planned-action
// model, the plan/report shapes, the Engine itself, and the platform/session
// gates. The typed errors the CLI matches with errors.As live in errors.go; the
// package doc lives in codec.go, which is the package's correctness core.

import (
	"os"
	"path"
	"path/filepath"
	"strconv"
	"strings"
	"time"

	"github.com/yandy-r/dotfiles/internal/exec"
	"github.com/yandy-r/dotfiles/internal/platform"
)

// repoFilesRel and repoRecommendedRel are the two repo-relative trees the
// engine reads and writes. files/ is machine-generated by export; recommended/
// is hand-authored and export never touches it.
const (
	repoFilesRel       = "plasma/files"
	repoRecommendedRel = "plasma/recommended"
)

// Directory and file modes. livePerm is KDE's own mode for a freshly created
// config file; dirPerm matches the rest of the repo's provisioning engines.
const (
	dirPerm  os.FileMode = 0o755
	livePerm os.FileMode = 0o600
)

// Lock defaults, taken from KConfig's own QLockFile timeout so a running Plasma
// and dotf wait the same amount of time for each other.
const (
	defaultLockTimeout = 45 * time.Second
	defaultLockPoll    = 100 * time.Millisecond
)

// systemColorSchemesDir is the distribution-provided colour-scheme directory
// the §7.4 guard falls back to when the caller supplies none. The guard reads an
// Engine field rather than this constant directly, so a caller can widen the
// search path to $XDG_DATA_DIRS and tests can point it at a t.TempDir and stay
// hermetic.
const systemColorSchemesDir = "/usr/share/color-schemes"

// Options are the run switches. Like symlink.Options this is a flat value with
// no baked-in defaults; the CLI layer constructs it explicitly and owns every
// default. The same value is passed to PlanExport, PlanApply, Execute, Diff,
// and Validate.
type Options struct {
	// DryRun disables every filesystem mutation. It is Execute's first
	// statement short-circuit.
	DryRun bool
	// Backup copies each live file the run will modify into Plan.BackupDir
	// before touching it.
	Backup bool
	// Validate is a CLI-layer switch only; the engine does not read it.
	// Engine.Validate always validates when called.
	Validate bool
	// Link plans ActionSymlink instead of ActionMerge for every selected file.
	Link bool
	// Unlink is Link's inverse: it plans ActionUnlink for every selected file
	// whose live path is a symlink, replacing the link with a real file holding
	// the merged content.
	//
	// It is an EXPLICIT opt-in rather than something a plain apply does on its
	// own. Reading a linked live path reads the repo bytes, so a linked file is
	// converged by construction and a plain apply has genuinely nothing to do
	// with it; silently materialising a copy instead would mean every headless
	// `dotf apply --plasma` tore down a deliberate --link deployment. Requiring
	// the flag is also what lets the link-mode guard stay narrow: with no
	// --unlink there is no transition to refuse.
	Unlink bool
	// Recommended layers plasma/recommended/ on top of plasma/files/. It is
	// mutually exclusive with Link: see LinkRecommendedError.
	Recommended bool
	// ShowVolatile includes EXPECTED live-only keys — the ones this file's own
	// VolatileGroups/VolatileKeys/VolatileValues rules deliberately strip on
	// export — in Diff's per-key output, tagged DiffExpectedVolatile.
	//
	// They are suppressed by default because they are neither drift nor news:
	// the strip table guarantees they can never appear in plasma/files/, so
	// reporting them alongside genuinely unmanaged keys buried the signal under
	// hundreds of [Tiling][<uuid>] and Id_* entries that are working exactly as
	// designed.
	ShowVolatile bool
	// Reload requests the post-apply live reload; without it Execute still
	// populates Plan.Reloads so the CLI can print the commands it did not run.
	Reload bool
	// Session is the detected KDE session state, resolved by the CLI via
	// DetectSession so the engine performs no environment lookups.
	Session SessionState
	// Display is the detected windowing system, resolved by the CLI via
	// DetectDisplayServer for the same reason. It selects which reloads can
	// actually work: see the kglobalaccel case in ReloadPlan.
	Display DisplayServer
}

// ActionKind classifies one planned file operation.
type ActionKind int

// Action kinds produced by PlanExport and PlanApply.
const (
	// ActionMerge rewrites a live INI file with the repo's keys merged in.
	ActionMerge ActionKind = iota
	// ActionCreateFile materialises an absent live file from the repo copy.
	ActionCreateFile
	// ActionCopyRaw is a verbatim byte copy of a FormatRaw member, in either
	// direction; FileAction.ToRepo says which.
	ActionCopyRaw
	// ActionExport writes a stripped repo file.
	ActionExport
	// ActionPrune deletes a repo file that no longer has surviving keys.
	ActionPrune
	// ActionSymlink replaces the live path with a symlink into the repo
	// (--link).
	ActionSymlink
	// ActionUnlink is ActionSymlink's inverse (--unlink): it replaces a
	// symlinked live path with a REAL file holding the merged content, restoring
	// copy mode. It is a distinct kind rather than an ActionMerge because the
	// merge path's convergence short-circuits would otherwise swallow it — a
	// linked path reads the repo's own bytes, so it is always "converged".
	ActionUnlink
	// ActionBackup copies a live file into Plan.BackupDir.
	ActionBackup
	// ActionSkip is a no-op: already converged, missing on the source side, or
	// gated out.
	ActionSkip
)

// String returns the stdout bucket name for a kind. The CLI's
// plasma.<bucket>=<paths> lines read this directly rather than switching on
// FileAction.Reason, which is human-readable prose only.
func (k ActionKind) String() string {
	switch k {
	case ActionMerge:
		return "merge"
	case ActionCreateFile:
		return "create"
	case ActionCopyRaw:
		return "copy"
	case ActionExport:
		return "export"
	case ActionPrune:
		return "prune"
	case ActionSymlink:
		return "link"
	case ActionUnlink:
		return "unlink"
	case ActionBackup:
		return "backup"
	case ActionSkip:
		return "skip"
	default:
		return "unknown"
	}
}

// KeyAction is one (group, key, locale) write. Action granularity is per key,
// not per file, so `plasma.change=` lines carry real detail.
//
// Every field here is one a renderer or a caller actually reads. The written
// entry's flag string used to be carried too and nothing ever read it: the
// authoritative flags live on the Doc the write is derived from, so a copy on
// the report was a second spelling of the same state that no consumer asked for
// and every future maintainer had to keep in sync. Add a field when a consumer
// exists, not in anticipation of one.
type KeyAction struct {
	// Group is the decoded group path segments; nil means the root group.
	Group []string
	// Key is the decoded bare key.
	Key string
	// Locale is the decoded locale tag ("" = none).
	Locale string
	// From is the current live value; nil when the key is absent live.
	From []byte
	// To is the value the run will write.
	To []byte
	// Tombstone is true when the repo entry is a [$d] deletion marker — the
	// only supported way for the repo to express "remove this live key".
	Tombstone bool
}

// FileAction is one file's worth of work.
type FileAction struct {
	// Spec is the FileSpec this action was derived from.
	Spec FileSpec
	// Kind is the operation to perform.
	Kind ActionKind
	// SrcAbs is the repo-side absolute path.
	SrcAbs string
	// DestAbs is the live-side absolute path.
	DestAbs string
	// Reason is human-readable prose. The renderer NEVER switches on it.
	Reason string
	// Keys lists the per-key writes a merge or create will perform. On an action
	// returned in Report.Applied these are the writes that ACTUALLY happened,
	// re-derived at write time.
	Keys []KeyAction
	// Content is the serialised target bytes.
	//
	// For an export it is the payload: the privacy scan and the dry-run preview
	// both see exactly what will land. For an apply of an INI file it is a
	// PREVIEW ONLY — a snapshot of what the merge would produce against the live
	// file as it stood at plan time. Execute re-derives the payload under the
	// lock (see Engine.writeMerged), because a running Plasma session writes
	// these files continuously and plan-time bytes go stale the instant a
	// confirmation prompt is displayed.
	//
	// Nil for ActionSymlink, ActionSkip, ActionPrune, and ActionBackup.
	Content []byte
	// Source is the repo-side document an apply writes into the live file:
	// plasma/files/<path> overlaid with plasma/recommended/<path> under
	// --recommended. It is what makes the write-time re-merge possible, and it
	// is the merge's only durable input — everything else comes from the live
	// file as read under the lock. Nil for every kind except ActionMerge and
	// ActionCreateFile.
	Source *Doc
	// Restated is set by Execute, never by a planner: the write-time re-merge
	// produced different bytes from the plan-time preview, because the live file
	// changed in between. The write is still correct and still non-destructive —
	// the merge is deterministic and never deletes a live key — but the user
	// asked to apply one thing and a slightly different thing landed, so it is
	// reported rather than absorbed.
	Restated bool
	// Mode is the file mode to write: the existing file's mode when it exists,
	// else 0o600 (KDE's own mode for freshly created config files).
	Mode os.FileMode
	// ToRepo records the write direction. ActionCopyRaw is bidirectional and
	// every other kind is fixed, but Execute receives only a *Plan and cannot
	// otherwise tell an export plan from an apply plan, so the discriminator
	// lives on the action rather than being re-derived.
	ToRepo bool
	// Err carries a non-fatal, per-file failure: a KConfig immutability marker,
	// or a file that exists but cannot be read. The file is skipped or its
	// write refused, the run continues, and Execute folds Err into its returned
	// error so the CLI can print a per-file line and exit 1.
	//
	// On an action returned in Report.Applied this is the WRITE-TIME failure
	// set, re-derived under the lock, not the plan-time preview's.
	Err error
}

// Plan is the read-only result of planning. Files are ordered by
// FileSpec.ApplyOrder, then path-lexicographically within a phase, except that
// a file's ActionBackup entry is always emitted immediately before that same
// file's mutating action so Execute's in-order loop copies the original before
// overwriting it.
type Plan struct {
	// Files are the planned per-file actions in execution order.
	Files []FileAction
	// BackupDir is <configDir>/dotf/plasma_backup_<epoch>, captured once at
	// plan time — even when Options.Backup is false — so Execute never
	// re-derives a timestamp mid-run and a test can read the path back.
	BackupDir string
	// Reloads is populated regardless of Options.Reload: without the flag they
	// are the commands the run declined to execute.
	Reloads []ReloadCommand
	// LookAndFeel is the look-and-feel package name read from
	// plasma/files/kdedefaults/package. ReloadPlan is pure and reads nothing,
	// so the name is resolved here, at plan time, where the file is already
	// being opened. Empty means "unknown", and the lookandfeel reload is then
	// not planned at all rather than planned with a missing argument.
	LookAndFeel string
	// Display is the windowing system the plan was built for, copied from
	// Options at plan time. ReloadPlan is pure and reads no environment, so
	// like LookAndFeel it is resolved here rather than looked up there.
	Display DisplayServer
	// Advisories are non-fatal notices the CLI prints to stderr, such as the
	// colour-scheme guard notice. The engine never writes to a stream itself.
	Advisories []string
	// LinkConflicts lists the config-dir-relative paths whose mode transition
	// only got planned because --dry-run authorised it. A real run without
	// --backup would be refused outright with a *LinkModeConflictError naming
	// exactly these files, so a preview that stayed silent about them printed a
	// confident plan the real invocation then rejected with exit 1. It is always
	// empty outside --dry-run: on a real run the refusal IS the error.
	LinkConflicts []string
}

// Report is the result of executing a plan.
type Report struct {
	// Applied lists actions actually performed; ActionSkip is excluded, so a
	// converged run reports applied=0. Nil under DryRun.
	Applied []FileAction
	// Planned is always the full plan, skips included.
	Planned []FileAction
	// DryRun records whether the run was a dry run.
	DryRun bool
	// Restated lists the config-dir-relative paths whose write-time re-merge
	// differed from the plan-time preview — the live file changed between
	// planning and writing, so the bytes that landed are derived from the newer
	// live file rather than from the preview the user saw. Never a failure; the
	// caller renders it as a notice.
	Restated []string
	// Reloaded lists the reload commands actually run (empty unless
	// Options.Reload and a live session).
	Reloaded []ReloadCommand
}

// Engine plans and executes plasma operations against a repo root and a KDE
// config directory.
type Engine struct {
	repoRoot  string
	configDir string
	r         exec.Runner
	// dataHome is the XDG data home. It is only read by the colour-scheme
	// guard.
	dataHome string
	// systemColorSchemes are the ORDERED distribution colour-scheme
	// directories; a field rather than a constant so tests stay hermetic.
	systemColorSchemes []string
	// lockTimeout and lockPoll govern <path>.lock acquisition. Fields rather
	// than constants so a test can prove the timeout without waiting 45s.
	lockTimeout time.Duration
	lockPoll    time.Duration
}

// NewEngine constructs an Engine. repoRoot is the dotfiles source tree;
// configDir is the resolved KDE config directory ($XDG_CONFIG_HOME, else
// $HOME/.config). The Runner is used only by Reload.
//
// dataHome and systemColorSchemes are the colour-scheme guard's only inputs and
// both are optional, because the package performs no environment lookups of its
// own (see DetectSession): an empty dataHome falls back to the historical
// derivation from configDir, and a nil or empty systemColorSchemes falls back to
// the single distribution directory. A caller that does not care about $XDG
// resolution therefore keeps the previous behaviour by passing "" and nil.
func NewEngine(repoRoot, configDir, dataHome string, systemColorSchemes []string, r exec.Runner) *Engine {
	if dataHome == "" {
		dataHome = filepath.Join(filepath.Dir(configDir), ".local", "share")
	}
	if len(systemColorSchemes) == 0 {
		systemColorSchemes = []string{systemColorSchemesDir}
	}
	return &Engine{
		repoRoot:           repoRoot,
		configDir:          configDir,
		r:                  r,
		dataHome:           dataHome,
		systemColorSchemes: append([]string(nil), systemColorSchemes...),
		lockTimeout:        defaultLockTimeout,
		lockPoll:           defaultLockPoll,
	}
}

// homeDir is the parent of the config dir. It is used only by the export
// privacy scan, which refuses to write an absolute home path into the repo.
func (e *Engine) homeDir() string { return filepath.Dir(e.configDir) }

// repoFilesDir is <repoRoot>/plasma/files, the tree export writes and apply
// reads.
func (e *Engine) repoFilesDir() string { return filepath.Join(e.repoRoot, repoFilesRel) }

// repoRecommendedDir is <repoRoot>/plasma/recommended, the hand-authored
// overlay. Export never writes here.
func (e *Engine) repoRecommendedDir() string { return filepath.Join(e.repoRoot, repoRecommendedRel) }

// livePath resolves a spec to its absolute path under the KDE config dir.
func (e *Engine) livePath(spec FileSpec) string {
	return filepath.Join(e.configDir, filepath.FromSlash(spec.Path))
}

// repoPath resolves a spec to its absolute path under plasma/files/.
func (e *Engine) repoPath(spec FileSpec) string {
	return filepath.Join(e.repoFilesDir(), filepath.FromSlash(spec.Path))
}

// recommendedPath resolves a spec to its absolute path under
// plasma/recommended/.
func (e *Engine) recommendedPath(spec FileSpec) string {
	return filepath.Join(e.repoRecommendedDir(), filepath.FromSlash(spec.Path))
}

// newBackupDir computes the run's backup directory. It lives under
// <configDir>/dotf/ rather than directly in the config dir so a stray kwinrc
// copy can never be picked up by KDE's own config scanning.
func (e *Engine) newBackupDir() string {
	return filepath.Join(e.configDir, "dotf",
		"plasma_backup_"+strconv.FormatInt(time.Now().Unix(), 10))
}

// checkSpec rejects a FileSpec whose path would escape the config dir or land
// inside a denylisted prefix. Both are pre-flight fences: the denylist in
// particular is a hard refusal, not merely an absence from DefaultFiles, so a
// future glob widening cannot reach a private key.
func checkSpec(spec FileSpec) error {
	p := spec.Path
	if p == "" || path.IsAbs(p) || strings.HasPrefix(p, "/") {
		return &UnsafePathError{Path: p}
	}
	for _, elem := range strings.Split(path.Clean(p), "/") {
		if elem == ".." {
			return &UnsafePathError{Path: p}
		}
	}
	if denylisted(p) {
		return &DenylistError{Path: p}
	}
	return nil
}

// denylisted reports whether a config-dir-relative path is fenced off by
// Denylist. A prefix ending in "/" fences a whole directory.
func denylisted(p string) bool {
	clean := path.Clean(p)
	for _, prefix := range Denylist() {
		if strings.HasSuffix(prefix, "/") {
			if strings.HasPrefix(clean+"/", prefix) {
				return true
			}
			continue
		}
		if clean == prefix {
			return true
		}
	}
	return false
}

// SupportLevel classifies how much of dotf plasma applies to a host.
type SupportLevel int

// Support levels. There is no Deferred level: KDE Plasma is a Linux desktop and
// macOS/Windows are permanent non-goals, not deferred work.
const (
	// SupportUnsupported: macOS, Windows, and any unknown OS.
	SupportUnsupported SupportLevel = iota
	// SupportSupported: any Linux family, WSL included.
	SupportSupported
)

// Support classifies a host without reading or running anything, mirroring
// sysconfig.Support. It lets doctor and apply skip the phase without
// constructing an Engine. WSL counts as supported for detection purposes even
// though it has no KDE session: the session check is DetectSession's job, and
// on a session-less host apply is still the correct fresh-machine behaviour.
func Support(info platform.Info) SupportLevel {
	if platform.IsLinuxFamily(info.OS) {
		return SupportSupported
	}
	return SupportUnsupported
}

// SessionState is the detected KDE session state.
type SessionState int

// Session states.
const (
	// SessionUnknown: neither KDE variable is set at all — a non-graphical
	// shell, where "no KDE" cannot be concluded.
	SessionUnknown SessionState = iota
	// SessionAbsent: the variables are set to something else — a different
	// desktop is running.
	SessionAbsent
	// SessionLive: a KDE Plasma session is running.
	SessionLive
)

// String renders a session state for the plasma.session= stdout line.
func (s SessionState) String() string {
	switch s {
	case SessionLive:
		return "live"
	case SessionAbsent:
		return "absent"
	default:
		return "unknown"
	}
}

// DetectSession classifies the KDE session from the environment. getenv is
// injected so the engine performs no environment lookups and the CLI passes
// os.Getenv.
//
// A session is Live when KDE_FULL_SESSION == "true" OR XDG_CURRENT_DESKTOP
// contains "KDE" as one of its colon-separated entries, case-insensitively. It
// is Unknown when neither variable is set at all, and Absent when they are set
// to something else.
func DetectSession(getenv func(string) string) SessionState {
	full := getenv("KDE_FULL_SESSION")
	desktop := getenv("XDG_CURRENT_DESKTOP")

	if strings.EqualFold(strings.TrimSpace(full), "true") {
		return SessionLive
	}
	for _, part := range strings.Split(desktop, ":") {
		if strings.EqualFold(strings.TrimSpace(part), "KDE") {
			return SessionLive
		}
	}
	if full == "" && desktop == "" {
		return SessionUnknown
	}
	return SessionAbsent
}
