// TestMain points XDG_CACHE_HOME at a throwaway directory for the whole test
// binary, so apply/link runs (which refresh the platform env cache) and the
// platform --write tests never touch the developer's real cache.
func TestMain(m *testing.M) {
	dir, err := os.MkdirTemp("", "dotf-test-cache-")
	if err != nil {
		panic(err)
	}
	_ = os.Setenv("XDG_CACHE_HOME", dir)
	code := m.Run()
	_ = os.RemoveAll(dir)
	os.Exit(code)
}

func TestRunPlatform_Flags(t *testing.T) {
	tests := []struct {
		name       string
		args       []string
		wantCode   int
		wantStdout string // prefix; "" means stdout must be empty
		wantFile   bool
	}{
		{name: "default", args: nil, wantStdout: "os="},
		{name: "env", args: []string{"--env"}, wantStdout: "# Generated by `dotf platform --write`; do not edit.\nexport DOTFILES_PLATFORM_SCHEMA=1\n"},
		{name: "write", args: []string{"--write"}, wantFile: true},
		{name: "env and write", args: []string{"--env", "--write"}, wantStdout: "# Generated", wantFile: true},
		{name: "unknown flag", args: []string{"--bogus"}, wantCode: 2},
		{name: "positional", args: []string{"extra"}, wantCode: 2},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Setenv("XDG_CACHE_HOME", t.TempDir())
			var stdout, stderr bytes.Buffer
			code := runPlatform(tt.args, &stdout, &stderr, exec.New())
			if code != tt.wantCode {
				t.Fatalf("code = %d, want %d (stderr %q)", code, tt.wantCode, stderr.String())
			}
			if tt.wantStdout == "" && stdout.Len() != 0 {
				t.Errorf("stdout = %q, want empty", stdout.String())
			}
			if !strings.HasPrefix(stdout.String(), tt.wantStdout) {
				t.Errorf("stdout = %q, want prefix %q", stdout.String(), tt.wantStdout)
			}
			if tt.wantCode == 0 && stderr.Len() != 0 {
				t.Errorf("stderr = %q, want empty", stderr.String())
			}

			path := filepath.Join(os.Getenv("XDG_CACHE_HOME"), "dotfiles", "platform.env")
			fi, err := os.Stat(path)
			if tt.wantFile != (err == nil) {
				t.Fatalf("cache file exists = %v, want %v", err == nil, tt.wantFile)
			}
			if !tt.wantFile {
				return
			}
			if fi.Mode().Perm() != 0o600 {
				t.Errorf("cache mode = %v, want 0600", fi.Mode().Perm())
			}
			if tt.wantStdout != "" {
				data, _ := os.ReadFile(path)
				if string(data) != stdout.String() {
					t.Errorf("cache content %q != printed env %q", data, stdout.String())
				}
			}
		})
	}
}

// TestRefreshPlatformCache_FailureWarnsOnce guards the apply/link contract: an
// unwritable cache yields exactly one stderr warning line, never a panic or
// an error the caller would turn into a non-zero exit.
func TestRefreshPlatformCache_FailureWarnsOnce(t *testing.T) {
	cache := t.TempDir()
	t.Setenv("XDG_CACHE_HOME", cache)
	target := filepath.Join(cache, "elsewhere")
	if err := os.Symlink(target, filepath.Join(cache, "dotfiles")); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(target, 0o700); err != nil {
		t.Fatal(err)
	}

	var stderr bytes.Buffer
	refreshPlatformCache(&stderr, exec.NewFake(), platform.Info{OS: platform.OSDebian})
	if got := strings.Count(stderr.String(), "\n"); got != 1 || !strings.Contains(stderr.String(), "warning") {
		t.Errorf("stderr = %q, want a single warning line", stderr.String())
	}
	if _, err := os.Stat(filepath.Join(target, "platform.env")); err == nil {
		t.Error("cache written through a symlinked directory")
	}
}
